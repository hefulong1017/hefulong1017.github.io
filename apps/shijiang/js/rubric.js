    weights: weights,
    grades: grades,
    rules: rules,
    examples: examples,
    weightOf: function (key) {
      for (var i = 0; i < weights.length; i++) if (weights[i].key === key) return weights[i].weight;
      return 0;
    },

    /**
     * 评分标准整块（表格 + 每维细则 + 等级线）。
     * 只在首页出现一次 —— 报告里不再重复，报告只讲「你这次为什么是这个分」。
     */
    html: function () {
      var esc = function (s) {
        return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
          return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
        });
      };

      var rows = weights.map(function (w) {
        return '<tr><td>' + esc(w.name) + '</td><td>' + w.weight + '%</td><td>' + esc(w.how) + '</td></tr>';
      }).join('');

      var det = weights.map(function (w) {
        var r = rules[w.key] || { lead: '', items: [] };
        return '<details class="rub-item">' +
          '<summary><span>' + esc(w.name) + '</span><b>' + w.weight + '%</b><i>' + r.items.length + ' 条规则</i></summary>' +
          '<p class="rub-lead">' + esc(r.lead) + '</p>' +
          '<ul class="rub-ul">' + r.items.map(function (it) {
            return '<li><b>' + esc(it[0]) + '</b><span>' + esc(it[1]) + '</span></li>';
          }).join('') + '</ul>' +
        '</details>';
      }).join('');

      var gradeRow = grades.map(function (g) {
        return '<div class="rg"><b>' + esc(g.key) + '</b><span>' + esc(g.range) + '</span><em>' + esc(g.desc) + '</em></div>';
      }).join('');

      return '<div class="rub-table-wrap"><table class="rub-table"><thead><tr>' +
          '<th>维度</th><th>权重</th><th>怎么采的</th></tr></thead><tbody>' + rows + '</tbody></table></div>' +
        '<div class="rub-list">' + det + '</div>' +
        '<div class="rub-grades">' + gradeRow + '</div>';
    }
